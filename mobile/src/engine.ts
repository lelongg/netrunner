import { applyFormatPools } from "./deckrules";

export type Side = "corp" | "runner";

export interface Card {
  title: string;
  code: string;
  side: "Corp" | "Runner";
  type: string;
  faction?: string;
  cost?: number;
  text?: string;
  [key: string]: unknown;
}

export interface DeckEntry {
  qty: number;
  card: Card;
}

export interface Deck {
  name: string;
  identity: Card;
  cards: DeckEntry[];
}

export interface PreconDeck {
  name: string;
  identity: string;
  cards: { qty: number; title: string }[];
}

export interface Matchup {
  key: string;
  title: string;
  corp: PreconDeck;
  runner: PreconDeck;
}

export interface GameHandle {
  readonly __game: unique symbol;
}

export interface Snapshot {
  readonly __snapshot: unique symbol;
}

export interface ActResult {
  ok: boolean;
}

export interface EngineApi {
  loadCards(cards: Card[]): number;
  loadDictionary(lang: string, ftl: string): void;
  setLanguage(lang: string): void;
  createGame(setup: unknown): GameHandle;
  view(game: GameHandle, side: Side | "spectator"): any;
  act(game: GameHandle, side: Side, command: string, args: unknown): ActResult;
  checkpoint(game: GameHandle): Snapshot;
  attempt(game: GameHandle, side: Side, command: string, args: unknown): void;
  restore(game: GameHandle, snapshot: Snapshot): void;
  mark(game: GameHandle): Snapshot;
  unchanged(game: GameHandle, snapshot: Snapshot): boolean;
  say(game: GameHandle, side: Side, user: unknown, text: string): ActResult;
  notify(game: GameHandle, text: string): ActResult;
  concede(game: GameHandle, side: Side): ActResult;
  winner(game: GameHandle): string | null;
  renderMessage(msg: unknown): string;
  precons(): Matchup[];
  availableCredits(game: GameHandle, side: Side, cid: unknown): Funds;
}

export interface Funds {
  total: number;
  pool: number;
  badPub: number;
  cards: number;
}

export interface CardDb {
  byTitle: Map<string, Card>;
  byCode: Map<string, Card>;
  all: Card[];
}

let loading: Promise<{ engine: EngineApi; db: CardDb }> | null = null;

async function fetchText(path: string) {
  const res = await fetch(new URL(path, document.baseURI));
  if (!res.ok) throw new Error(`${path}: ${res.status}`);
  return res.text();
}

export function importEngine(): Promise<EngineApi> {
  // @ts-expect-error generated by shadow-cljs (npm run engine)
  return import("../engine/engine.js");
}

export let engineHasFrench = false;

export function loadEngine() {
  loading ??= (async () => {
    const enginePromise = importEngine();
    const [engine, cards, codes, ...ftl] = await Promise.all([enginePromise, fetchText("data/cards.json").then((t) => JSON.parse(t) as Card[]), fetchText("data/codes.json").then((t) => JSON.parse(t) as Record<string, string>), fetchText("i18n/en/messages.ftl"), fetchText("i18n/en/ui.ftl")]);
    fetchText("data/formats.json")
      .then((t) => applyFormatPools(JSON.parse(t)))
      .catch(() => {});
    engine.loadCards(cards);
    engine.loadDictionary("en", ftl[0] + "\n" + ftl[1]);
    engine.setLanguage("en");
    Promise.all([fetchText("i18n/fr/messages.ftl"), fetchText("i18n/fr/ui.ftl")])
      .then(([m, u]) => {
        engine.loadDictionary("fr", m + "\n" + u);
        engine.setLanguage("en");
        engineHasFrench = true;
      })
      .catch(() => {});
    const byTitle = new Map(cards.map((c) => [c.title, c]));
    const byCode = new Map<string, Card>();
    for (const [code, title] of Object.entries(codes)) {
      const card = byTitle.get(title);
      if (card) byCode.set(code, card);
    }
    return { engine, db: { byTitle, byCode, all: cards } };
  })();
  return loading;
}

const FACE_INDEX: Record<string, number> = { back: 0, brewery: 0, tank: 1, greenhouse: 2, tenure: 0, subsurface: 1, disposal: 2 };
const FACE_BASE: Record<string, string> = { brewery: "08012", tank: "08012", greenhouse: "08012", sync: "09001" };

export function faceIndex(card: any): number | undefined {
  return card?.face ? FACE_INDEX[String(card.face)] : undefined;
}

export function faceCode(card: any): string | undefined {
  const code: string | undefined = card?.code;
  if (!code) return code;
  const base = FACE_BASE[code] ?? code.replace(/flip$/, "");
  const i = faceIndex(card);
  return i == null ? base : `${base}-${i}`;
}

export function cardImage(code: string | undefined, size: "small" | "medium" | "large" | "xlarge" = "medium") {
  return code ? `https://card-images.netrunnerdb.com/v2/${size}/${code}.${size === "xlarge" ? "webp" : "jpg"}` : undefined;
}
